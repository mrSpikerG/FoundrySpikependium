import { SPELL_NAMES } from "../names.mjs";

const link = (key, text) => `@UUID[${ref(key)}]{${text}}`;

/**
 * Список заклинаний: имена по уровням; заклинания вне SRD попадают в «несвязанные».
 * unlinkedMeta: { "Название": [уровень, школа] }
 */
function spellList(byLevel, unlinkedMeta = {}) {
  const uuids = new Set();
  const unlinked = [];
  for ( const [lvl, names] of Object.entries(byLevel) ) {
    for ( const n of names ) {
      const uuid = spellUuid(n);
      if ( uuid ) uuids.add(uuid);
      else {
        const [level, school] = unlinkedMeta[n] ?? [Number(lvl), ""];
        unlinked.push({ name: SPELL_NAMES[n] ? `${n} (${SPELL_NAMES[n]})` : n, level, school, custom: "Нет в SRD — добавьте из своей книги" });
      }
    }
  }
  return { uuids: [...uuids], unlinked };
}

